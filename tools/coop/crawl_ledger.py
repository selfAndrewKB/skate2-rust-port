def families():
    """eChallengeTypes by number, from `coop/rules.rs` so the names never drift."""
    text = (ROOT / 'crates/skate2-core/src/coop/rules.rs').read_text(encoding='utf-8')
    out = {}
    for name, value in re.findall(r'pub const ([A-Z_]+): i32 = (\d+);', text):
        out[int(value)] = name.lower().replace('_', ' ')
    out.update(MORE_FAMILIES)
    return out


# `eChallengeTypes` the rules table does not name: 35, 40, 44, 45 from `map_icons.rs`; the rest
# read off the missions' names (marked †) until the enumeration is found in the binary.
MORE_FAMILIES = {2: 'demo †', 4: 'S.K.A.T.E. †', 35: 'create-a-spot', 38: 'photo (team) †', 39: 'film (pool team) †', 40: 'spot film', 41: 'pro film †', 43: 'film team †', 44: 'no icon', 45: 'property (teleport)'}
COMPETE = {1, 3, 10, 11, 12, 13, 15, 16, 18, 19, 20, 21, 26, 27}
BEST_OF = {8, 9, 31, 33}


def kind(global_type):
    return 'main' if global_type in (3, 4) else 'location' if global_type == 2 else 'none'


def table_rule(name, family):
    """The built-in table's rule, as `RuleTable::builtin` reads (prefix, then family, then Anyone)."""
    if name.startswith('m_1a_'):
        return 'Everyone'
    if family in (0, 17):
        return 'Everyone'
    if family in COMPETE:
        return 'Compete'
    if family in BEST_OF:
        return 'BestOf'
    return 'Anyone'


def lines(path):
    try:
        return path.read_text(encoding='utf-8', errors='replace').splitlines()
    except OSError:
        return []


NOISE = re.compile(r'controlled frame|unlit diffuse|CONTROLLED FIRST|first-test boot|coop: world stream at|coop: live audit|DMO models')
UNKNOWN = re.compile(r'unknown|unported|unsupported|unhandled|not ported|not implemented|unimplemented|script error|ScriptError|TODO|ignored|provisional', re.I)


def normalize(line):
    line = re.sub(r'0x[0-9a-f]+|\b[0-9a-f]{8,}\b', '#', line)
    line = re.sub(r'(?<=[ (:])-?\d+(\.\d+)?', 'N', line)
    return line[:200]


def compress(states):
    """The script's path as run-lengths, the trailing loop folded: initial→setup→(check_ai→wait)×542."""
    names = [s for _, s in states]
    if not names:
        return '', None, 0
    # the trailing cycle: the shortest period that repeats at least three times at the end
    loop, times = None, 0
    for period in range(1, 5):
        if len(names) >= 3 * period:
            cycle = names[-period:]
            n = 0
            while len(names) >= (n + 1) * period and names[-(n + 1) * period:len(names) - n * period] == cycle:
                n += 1
            if n >= 3:
                loop, times = cycle, n
                break
    head = names[:len(names) - times * len(loop)] if loop else names
    path = []
    for name in head:
        if path and path[-1][0] == name:
            path[-1][1] += 1
        else:
            path.append([name, 1])
    text = '→'.join(f'{n}×{c}' if c > 1 else n for n, c in path)
    if loop:
        text += ('→' if text else '') + '(' + '→'.join(loop) + f')×{times}'
    return text, loop, times


