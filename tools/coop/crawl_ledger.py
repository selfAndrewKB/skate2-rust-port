def census(name):
    """The offline census audit of the two kept seat logs (`tools/coop/sync_audit.py`)."""
    a, b = EVIDENCE / f'crawl-{name}-seat-1.log', EVIDENCE / f'crawl-{name}-seat-2.log'
    if not (a.exists() and b.exists()):
        return None
    return census_audit(a, b)


def seat(name, path):
    log = lines(path)
    r = {'log': str(path.relative_to(ROOT.parent)) if path.exists() else None, 'lines': len(log)}
    if not log:
        return r
    stop = next((i for i, l in enumerate(log) if l.startswith('crawl: stop')), None)
    r['stop'] = log[stop][len('crawl: stop '):] if stop is not None else None
    if stop is not None:
        log = log[:stop]  # what follows is the bench's teardown
    g = lambda pat: [m for m in (re.search(pat, l) for l in log) if m]  # noqa: E731
    m = g(rf'diagnostic: complete challenge {re.escape(name)} at round tick (\d+)(?:: (\w+))?')
    # the result is logged since coop-v0.9.1; a line without one (the 2026-11-10 crawl) counts as completed, unverified
    r['completed'] = int(m[-1].group(1)) if m and m[-1].group(2) in (None, 'true') else None
    r['completed_unverified'] = bool(m) and m[-1].group(2) is None
    m = g(rf'diagnostic: execute {re.escape(name)} at round tick (\d+): (\w+)')
    r['executed'] = m[-1].group(2) == 'true' if m else None
    m = g(r'diagnostic: won the main challenge at round tick (\d+): (\d+) objectives completed')
    r['won'] = (int(m[-1].group(1)), int(m[-1].group(2))) if m else None
    states = [(int(m.group(1)), m.group(2)) for m in g(rf'career graph {re.escape(name)} @(\d+): enter (\w+)')]
    r['states'] = states
    r['path'], r['loop'], r['loop_times'] = compress(states)
    r['last_state'] = states[-1] if states else None
    r['cleanup'] = next((t for t, s in states if s == 'challenge_cleanup'), None)
    r['complete'] = next((t for t, s in states if s == 'complete'), None)
    m = g(r'coop: campaign save at session (\d+) round tick (\d+): (\d+) B, hash ([0-9a-f]+)')
    r['save'] = {'session': int(m[-1].group(1)), 'tick': int(m[-1].group(2)), 'bytes': int(m[-1].group(3)), 'hash': m[-1].group(4)} if m else None
    m = g(rf'coop: rule: {re.escape(name)} \(([0-9a-f]+)\) is (\w+(?: \{{[^}}]*\}})?): objectives for players \[([^\]]*)\]')
    r['rule'] = {'key': m[0].group(1), 'rule': m[0].group(2), 'players': m[0].group(3)} if m else None
    obj = defaultdict(set)
    for m in g(r'coop: objective ([0-9a-f]+) of player (\d+): (\w+) -> (\w+)'):
        obj[m.group(2)].add((m.group(1), m.group(4)))
    r['objectives'] = {p: {'copies': len({o for o, _ in v}), 'complete': len({o for o, s in v if s == 'Complete'}), 'failed': len({o for o, s in v if s == 'Failed'})} for p, v in sorted(obj.items())}
    r['withheld'] = len(g(r': withheld$'))
    groups = g(r'coop: presentation group (\d+): event (\d+) of (\d+), kind (\d+)')
    r['presentation'] = {'groups': len({m.group(1) for m in groups}), 'events': len(groups), 'kinds': sorted({int(m.group(4)) for m in groups}), 'finished': len(g(r'presentation group \d+ finished'))}
    r['scenes'] = [(m.group(1), int(m.group(2))) for m in g(r'coop: scene (\S+) starts at tick (\d+)')]
    r['scene_characters'] = [int(m.group(1)) for m in g(r'coop: scene \S+ instanced (\d+) characters')]
    r['triggers'] = len(g(r'coop: trigger [0-9a-f]+ entered by player'))
    r['notes_applied'] = len(g(r'coop: (?:prompt|note) .*applied|answer .* applied'))
    # without a stop marker (the first runs), a disconnect in the last 20 lines is the teardown's
    r['failed'] = [l[:160] for i, l in enumerate(log) if re.search(r'panicked|kicked', l) or ('disconnected' in l and (stop is not None or len(log) - i > 20))][:3]
    errs = Counter(normalize(re.sub(r'^.*career script error in ', '', l)) for l in log if 'career script error' in l)
    r['script_errors'] = [{'error': e, 'count': c} for e, c in errs.most_common()]
    r['teleport_unknown'] = [l[8:160] for l in log if 'teleport to unknown location' in l][:3]
    r['ai_players'] = [f'{m.group(1)}: {m.group(2)}' for m in g(r'career: AI player (\d+) character 0x[0-9a-f]+ names .* => \("([^"]*)"')]
    unk = Counter(normalize(l) for l in log if UNKNOWN.search(l) and not NOISE.search(l) and 'career script error' not in l and 'ScriptError' not in l)
    r['unknown'] = [{'line': e, 'count': c} for e, c in unk.most_common(12)]
    # synchronization
    audit = {'windows': 0, 'samples': 0, 'pos_ok': 0, 'yaw_ok': 0, 'speed_ok': 0, 'flags_ok': 0, 'worst_pos_m': 0.0, 'worst_yaw_deg': 0}
    for m in g(r'coop: live audit at (\d+): (\d+) samples; position within [\d.]+ m (\d+) \(worst ([\d.]+) m, \w+\), yaw within \d+° (\d+) \(worst (\d+)°, \w+\), speed within [\d.]+ m/s (\d+), flags equal (\d+)'):
        audit['windows'] += 1
        audit['samples'] += int(m.group(2))
        audit['pos_ok'] += int(m.group(3))
        audit['worst_pos_m'] = max(audit['worst_pos_m'], float(m.group(4)))
        audit['yaw_ok'] += int(m.group(5))
        audit['worst_yaw_deg'] = max(audit['worst_yaw_deg'], int(m.group(6)))
        audit['speed_ok'] += int(m.group(7))
        audit['flags_ok'] += int(m.group(8))
    r['audit'] = audit
    ws = {'windows': 0, 'peak_entity_samples': 0, 'peak_bps': 0, 'peak_owned': 0, 'peak_pedestrians': 0, 'peak_puppets': 0, 'peak_props_known': 0, 'peak_props_owned': 0, 'contacts_sent': 0, 'contacts_applied': 0, 'contacts_refused': 0, 'contacts_confirmed': 0, 'older_epoch': 0, 'bytes': 0}
    for m in g(r'coop: world stream at (\d+): (\d+) runs, (\d+) entity samples, (\d+) prop samples, (\d+) B \((\d+) B/s, (\d+) B/s per streamed pedestrian\), (\d+) owned in range of (\d+) pedestrians here, (\d+) puppets, (\d+) props owned of (\d+) known, contacts sent (\d+) applied (\d+) confirmed (\d+)(?: refused (\d+))?, (\d+) records ignored'):
        v = [int(x) if x is not None else 0 for x in m.groups()]  # refused: logged since the stand-up fix
        ws['windows'] += 1
        ws['peak_entity_samples'] = max(ws['peak_entity_samples'], v[2])
        ws['bytes'] += v[4]
        ws['peak_bps'] = max(ws['peak_bps'], v[5])
        ws['peak_owned'] = max(ws['peak_owned'], v[7])
        ws['peak_pedestrians'] = max(ws['peak_pedestrians'], v[8])
        ws['peak_puppets'] = max(ws['peak_puppets'], v[9])
        ws['peak_props_owned'] = max(ws['peak_props_owned'], v[10])
        ws['peak_props_known'] = max(ws['peak_props_known'], v[11])
        ws['contacts_sent'] += v[12]
        ws['contacts_applied'] += v[13]
        ws['contacts_confirmed'] += v[14]
        ws['contacts_refused'] += v[15]
        ws['older_epoch'] += v[16]
    r['world'] = ws
    r['handoffs'] = len(g(r'coop: .*handed to')) ; r['promotions'] = len(g(r'coop: .*promoted')); r['demotions'] = len(g(r'coop: .*demoted')); r['knockdowns'] = len(g(r'coop: .*knocked down'))
    stalls = [int(m.group(2)) for m in g(r'online: round at tick (\d+): \d+ ready, stalled (\d+) of the last \d+ ticks')]
    r['stalled_ticks'] = sum(stalls)
    pace = g(r'online: \w+: (\d+) of (\d+) ticks at or past the newest sample, delay ([\d.]+), pace ([\d.]+), (\d+) teleport frames')
    r['starved_ticks'] = sum(int(m.group(1)) for m in pace)
    r['teleport_frames'] = sum(int(m.group(5)) for m in pace)
    r['round_tick_last'] = max([t for t, _ in states] + [0])
    return r


def server(name, path):
    log = lines(path)
    if not log:
        return None
    r = {'log': str(path.relative_to(ROOT.parent))}
    m = [re.search(r'build ([0-9a-f]{8})', l) for l in log]
    r['build'] = next((x.group(1) for x in m if x), None)
    r['round_started'] = [l[l.index('campaign round'):][:80] for l in log if 'campaign round' in l and 'started with' in l]
    r['save_lines'] = [l[l.index('campaign save'):][:140] for l in log if 'campaign save from' in l]
    r['agrees'] = any('agrees' in l for l in r['save_lines'])
    return r


def _errs(s):
    return ' '.join(e['error'] for e in s.get('script_errors', []))


def _last(s):
    return (s.get('last_state') or (0, ''))[1]


CAUSES = [
    ('crash', lambda m: any('panicked' in f for s in m['seats'].values() for f in s.get('failed', []))),
    ('net: dropped', lambda m: any(s.get('failed') for s in m['seats'].values())),
    ('no log', lambda m: any(not s.get('lines') for s in m['seats'].values())),
    ('not executed', lambda m: m['kind'] == 'main' and any(s.get('lines') and not s.get('executed') for s in m['seats'].values())),
    ('not completed by name', lambda m: m['kind'] != 'main' and any(s.get('completed') is None for s in m['seats'].values())),
    # the co-op causes come first: a lockstep campaign owes identical scripts on every seat
    ('co-op: seats diverged', lambda m: m.get('paths_agree') is False),
    ('co-op: out of step', lambda m: m.get('paths_agree') and not m['in_step']),
    ('port: unknown locator', lambda m: any('unknown location' in _errs(s) or (m['kind'] == 'location' and s.get('teleport_unknown')) for s in m['seats'].values())),
    ('port: AI skater', lambda m: any((s.get('loop') and any(x.startswith('check_') for x in s['loop'])) or 'AI skater manager' in _errs(s) for s in m['seats'].values())),
    ('port: AI assets never load', lambda m: any(_last(s) == 'wait_for_assetload' and s.get('ai_players') for s in m['seats'].values())),
    ('script error', lambda m: any(s.get('script_errors') for s in m['seats'].values())),
]


def classify(m):
    if m['passed']:
        return '—'
    for cause, test in CAUSES:
        if test(m):
            return cause
    s = m['seats'][1]
    if s.get('loop'):
        return f"waits: ({'→'.join(s['loop'])})×{s['loop_times']}"
    if s.get('last_state'):
        return f"stops in {s['last_state'][1]}"
    return 'unknown'


def verdict_from_logs(m):
    seats = m['seats']
    if m['kind'] == 'main':
        both = all(s.get('executed') and (s.get('cleanup') is not None or s.get('complete') is not None) for s in seats.values())
    else:
        both = all(s.get('completed') is not None for s in seats.values())
    saves = [s.get('save') for s in seats.values()]
    if both and all(saves) and len({s['hash'] for s in saves}) == 1:
        return 'PASS'
    if both and not any(saves):
        return 'PASS (no save)'
    if both:
        return 'PASS (saves differ)'
    if m['kind'] == 'main' and any(s.get('lines') and not s.get('executed') for s in seats.values()):
        return 'NOT EXECUTED'
    if any('panicked' in f for s in seats.values() for f in s.get('failed', [])):
        return 'CRASHED'
    if any(s.get('failed') for s in seats.values()):
        return 'DROPPED'
    if not any(s.get('lines') for s in seats.values()):
        return 'NOT RUN'
    return 'STOPPED'


def runs():
    """Every crawl report: run id (file stem), its rows (mission → verdict), in date order."""
    out = []
    for path in sorted(EVIDENCE.glob('*-crawl*.md'), key=lambda p: (p.name[:10], p.stat().st_mtime)):
        rows = {}
        for l in lines(path):
            m = re.match(r'\| `([^`]+)` \| ([^|]+?) \|', l)
            if m:
                rows[m.group(1)] = m.group(2).strip()
        if rows:
            out.append({'run': path.stem, 'report': str(path.relative_to(ROOT.parent)), 'rows': rows})
    return out


def notes():
    """`- \`mission\`: text` lines under `## Notes` in missions.md, and `- run \`id\`: text`."""
    text = LEDGER.read_text(encoding='utf-8') if LEDGER.exists() else ''
    tail = text.split('## Notes', 1)[1] if '## Notes' in text else ''
    per_mission, per_run = {}, {}
    for m in re.finditer(r'^- run `([^`]+)`: (.+?)(?=\n- |\n\n|\Z)', tail, re.M | re.S):
        per_run[m.group(1)] = ' '.join(m.group(2).split())
    for m in re.finditer(r'^- `([^`]+)`: (.+?)(?=\n- |\n\n|\Z)', tail, re.M | re.S):
        per_mission[m.group(1)] = ' '.join(m.group(2).split())
    return per_mission, per_run, text


def pct(a, b):
    return f'{100 * a / b:.1f} %' if b else '—'


def main():
    fam = families()
    all_runs = runs()
    note_mission, note_run, old = notes()
    if not os.environ.get('SKATE2_CAREER_DB'):
        sys.exit('crawl_ledger: SKATE2_CAREER_DB is needed (the missions\' kinds and families come from the career db); nothing written')
    names = {n: (t, g) for n, t, g in crawl.missions()}
    for run in all_runs:
        for n in run['rows']:
            names.setdefault(n, (None, None))
    missions = []
    for name in sorted(names):
        family_id, global_type = names[name]
        m = {'mission': name, 'family_id': family_id, 'global': global_type, 'kind': kind(global_type) if global_type is not None else 'main',
             'family': fam.get(family_id, f'type {family_id}') if family_id is not None else '?',
             'seats': {s: seat(name, EVIDENCE / f'crawl-{name}-seat-{s}.log') for s in (1, 2)},
             'server': server(name, EVIDENCE / f'crawl-{name}-server.log'),
             'census': census(name),
             'history': [(r['run'], r['rows'][name]) for r in all_runs if name in r['rows']]}
        m['table_rule'] = table_rule(name, family_id) if family_id is not None else '?'
        logged = next((s['rule']['rule'] for s in m['seats'].values() if s.get('rule')), None)
        m['rule'] = logged or (m['table_rule'] + ' (table)')
        m['verdict'] = verdict_from_logs(m) if any(s.get('lines') for s in m['seats'].values()) else (m['history'][-1][1] if m['history'] else 'NOT RUN')
        m['passed'] = m['verdict'].startswith('PASS')
        s1, s2 = m['seats'][1], m['seats'][2]
        l1, l2 = s1.get('last_state'), s2.get('last_state')
        evidence = bool(s1.get('lines') and s2.get('lines') and (s1.get('states') or s2.get('states')))
        m['in_step'] = (l1 == l2) if evidence else None  # None: no mission-named state on either seat
        m['paths_agree'] = (s1.get('path') == s2.get('path')) if evidence else None
        m['cause'] = classify(m) if m['verdict'] != 'NOT RUN' else '—'
        m['note'] = note_mission.get(name, '')
        missions.append(m)

    # ---- the ledger
    ran = [m for m in missions if m['verdict'] != 'NOT RUN']
    counts = Counter(m['verdict'] for m in missions)
    causes = Counter(m['cause'] for m in missions if not m['passed'] and m['verdict'] != 'NOT RUN')
    L = []
    L.append(BEGIN)
    L.append('')
    L.append(f"**Standing:** {len(missions)} missions, {len(ran)} run, {sum(1 for m in ran if m['passed'])} pass; "
             + ', '.join(f'{v} {c}' for v, c in sorted(counts.items())) + '.')
    if causes:
        L.append('')
        L.append('**Why the rest stop:** ' + ', '.join(f'{c} ×{n}' for c, n in causes.most_common()) + '.')
    L.append('')
    L.append('### Runs')
    L.append('')
    L.append('| Run | Missions | Verdicts | Build, commit | Report |')
    L.append('| --- | --- | --- | --- | --- |')
    for r in all_runs:
        vc = Counter(v.split(' (')[0] for v in r['rows'].values())
        L.append(f"| `{r['run']}` | {len(r['rows'])} | {', '.join(f'{v} {c}' for v, c in sorted(vc.items()))} | {note_run.get(r['run'], '(not noted)')} | `{r['report']}` |")
    L.append('')
    L.append('### Missions')
    L.append('')
    L.append('Verdicts: PASS (both seats through `challenge_cleanup`, or through `complete` for a challenge that completes on execute, saves agreeing), PASS (no save), PASS (saves differ), STOPPED, NOT EXECUTED, CRASHED, DROPPED, NOT RUN. '
             '"In step": both seats\' scripts ended in the same state at the same round tick. The details, one section a mission: [missions-detail](missions-detail.md).')
    L.append('')
    L.append('Kind, from `challenge_global_data.Global`: main (3, 4: executed and won), location (2: executed, then completed by name), none (0: completed by name). Families marked † are named from the missions, the enumeration being unread.')
    L.append('')
    L.append('| Mission | Family | Kind | Rule | Verdict | Stopped at | Cause | In step | Runs | Note |')
    L.append('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for m in missions:
        s1 = m['seats'][1]
        last = s1.get('last_state')
        where = '—' if m['passed'] else (f"`{last[1]}` @{last[0]}" if last else '—')
        hist = ', '.join(f"{run.split('-crawl')[0]}{run.split('-crawl')[1] or ''}: {v}" for run, v in m['history']) if m['history'] else '—'
        step = '—' if m['verdict'] == 'NOT RUN' or m['in_step'] is None else ('yes' if m['in_step'] else 'no')
        L.append(f"| `{m['mission']}` | {m['family']} | {m['kind']} | {m['rule']} | {m['verdict']} | {where} | {m['cause']} | {step} | {hist} | {m['note']} |")
    # ---- synchronization
    L.append('')
    L.append('### Synchronization, per mission (seat 1\'s view)')
    L.append('')
    L.append('The live audit compares every streamed pedestrian\'s puppet with its owner\'s sample (tolerances 0.5 m, 5°, 0.5 m/s); the world stream line counts what was shared. '
             'Zero samples means no pedestrian was near both seats (the bench\'s teleports put them at the mission\'s locator). Stalled: round ticks the lockstep waited for a peer; starved: ticks the interpolation ran past its newest sample.')
    L.append('')
    L.append('| Mission | Audit samples | Position ok | Yaw ok | Speed ok | Flags ok | Worst pos / yaw | Peak pedestrians (owned / puppets) | Peak B/s | Props known | Contacts sent/applied/confirmed/refused | Handoffs | Stalled / starved ticks | Last round tick |')
    L.append('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for m in ran:
        s = m['seats'][1]
        if not s.get('lines'):
            continue
        a, w = s['audit'], s['world']
        L.append(f"| `{m['mission']}` | {a['samples']} | {pct(a['pos_ok'], a['samples'])} | {pct(a['yaw_ok'], a['samples'])} | {pct(a['speed_ok'], a['samples'])} | {pct(a['flags_ok'], a['samples'])} | {a['worst_pos_m']:.2f} m / {a['worst_yaw_deg']}° | {w['peak_pedestrians']} ({w['peak_owned']} / {w['peak_puppets']}) | {w['peak_bps']} | {w['peak_props_known']} | {w['contacts_sent']}/{w['contacts_applied']}/{w['contacts_confirmed']}/{w['contacts_refused']} | {s['handoffs']} | {s['stalled_ticks']} / {s['starved_ticks']} | {s['round_tick_last']} |")
    # ---- the states catalog
    seen = defaultdict(set)
    terminal = Counter()
    for m in ran:
        for s in m['seats'].values():
            for _, st in s.get('states', []):
                seen[st].add(m['mission'])
            if not m['passed'] and s.get('last_state'):
                terminal[s['last_state'][1]] += 1
    L.append('')
    L.append('### The census audit, per mission (both seats\' dumps paired)')
    L.append('')
    L.append('`tools/coop/sync_audit.py` over the two kept logs: every pedestrian both seats listed at the same round tick (one dump every 60 ticks), each shared field compared (position 0.5 m, yaw 5°, speed 0.5 m/s, flags, model and down exact); "one seat only" counts entities the other seat had not spawned or had culled; "open" counts the field divergences still standing at the last dump. The graph and the moods are local by design and not compared.')
    L.append('')
    L.append('| Mission | Dumps | Paired | One seat only (1 / 2) | Position | Yaw | Speed | Flags | Down | Model | Owner clash | Open at end |')
    L.append('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
    for m in ran:
        c = m.get('census')
        if not c:
            L.append(f"| `{m['mission']}` | — | — | — | — | — | — | — | — | — | — | — |")
            continue
        p = c['paired']
        cpct = lambda f: f"{100.0 * c['shared'][f]['ok'] / p:.1f} %" if p else '—'  # noqa: E731
        cworst = lambda f, u: f" ({c['shared'][f]['worst']:.1f}{u})" if c['shared'][f]['at'] else ''  # noqa: E731
        L.append(f"| `{m['mission']}` | {c['dumps']} | {p} | {c['only_a']} / {c['only_b']} | {cpct('position')}{cworst('position', ' m')} | {cpct('yaw')}{cworst('yaw', '°')} | {cpct('speed')}{cworst('speed', ' m/s')} | {cpct('flags')} | {cpct('down')} | {cpct('model')} | {c['owner_disagree']} | {len(c['open'])} |")
    L.append('')
    L.append('### The scripts\' states seen')
    L.append('')
    L.append('Every career-graph state the crawl entered, in how many missions, and how often a stopped mission ended in it. A state that only ever ends missions is where the port or co-op owes work.')
    L.append('')
    L.append('| State | Missions | Ends a stopped mission |')
    L.append('| --- | --- | --- |')
    for st, ms in sorted(seen.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        L.append(f'| `{st}` | {len(ms)} | {terminal.get(st, 0)} |')
    # ---- unknowns
    unk = Counter()
    unk_where = defaultdict(set)
    errs = Counter()
    err_where = defaultdict(set)
    for m in ran:
        for s in m['seats'].values():
            for u in s.get('unknown', []):
                unk[u['line']] += u['count']
                unk_where[u['line']].add(m['mission'])
            for e in s.get('script_errors', []):
                errs[e['error']] += e['count']
                err_where[e['error']].add(m['mission'])
    L.append('')
    L.append('### Script errors')
    L.append('')
    if errs:
        L.append('| Error (numbers and ids as #/N) | Lines | Missions |')
        L.append('| --- | --- | --- |')
        for e, c in errs.most_common(60):
            ms = sorted(err_where[e])
            L.append(f"| `{e}` | {c} | {len(ms)}: {', '.join(f'`{x}`' for x in ms[:6])}{'…' if len(ms) > 6 else ''} |")
    else:
        L.append('None logged.')
    L.append('')
    L.append('### Unknown, unported or ignored, as the logs say it')
    L.append('')
    L.append('Every distinct line matching unknown/unported/unsupported/unhandled/not ported/ignored/provisional (ids and numbers folded), with the missions it appeared in. The known noise (render diagnostics, the stream and audit lines) is excluded.')
    L.append('')
    if unk:
        L.append('| Line | Count | Missions |')
        L.append('| --- | --- | --- |')
        for u, c in unk.most_common(80):
            ms = sorted(unk_where[u])
            L.append(f"| `{u}` | {c} | {len(ms)}: {', '.join(f'`{x}`' for x in ms[:5])}{'…' if len(ms) > 5 else ''} |")
    else:
        L.append('None logged.')
    L.append('')
    L.append(END)
    generated = '\n'.join(L)

    if BEGIN in old and END in old:
        if old.index(BEGIN) > old.index(END):
            sys.exit('crawl_ledger: the ledger markers are reversed in missions.md; nothing written')
        new = old[:old.index(BEGIN)] + generated + old[old.index(END) + len(END):]
    else:
        # the markers are gone (an edit above them): the hand-kept Notes are kept as they stand
        notes_text = old[old.index('## Notes'):] if '## Notes' in old else 'Hand-kept, one line a mission (`- \\`mission\\`: text`) or a run (`- run \\`id\\`: build, commit`); merged into the tables above.\n'
        if not notes_text.startswith('## Notes'):
            notes_text = '## Notes\n\n' + notes_text
        new = HEADER + generated + '\n\n' + notes_text
    LEDGER.write_text(new, encoding='utf-8')

    # ---- the detail document
    D = ['# The missions in detail', '',
         'Generated by `tools/coop/crawl_ledger.py` from each mission\'s newest kept crawl log; do not edit. The ledger: [missions](missions.md). '
         'Ticks are round ticks (60 a second); the crawl executes the mission at 900 and wins it by diagnostic (300 ticks after its `challenge_running` since 2026-11-11; at 1800 before), so a script\'s own completion, if any, is earlier than its cleanup.', '']
    for m in ran:
        D.append(f"## `{m['mission']}`")
        D.append('')
        c = m.get('census')
        if c and c['paired']:
            fields = ', '.join(f"{f} {100.0 * c['shared'][f]['ok'] / c['paired']:.1f} %" for f in ('position', 'yaw', 'speed', 'flags', 'down', 'model'))
            opened = '; '.join(f"{w} {f} since {t}" for t, w, f in c['open'][:8]) + ('…' if len(c['open']) > 8 else '')
            census_line = f"Census audit: {c['dumps']} dumps, {c['paired']} pairs, one seat only {c['only_a']} / {c['only_b']}, owner clashes {c['owner_disagree']}; {fields}; open at the end: {len(c['open'])}{(' (' + opened + ')') if opened else ''}."
        else:
            census_line = 'Census audit: no dumps paired.'
        D.append(f"Family {m['family']} ({m['family_id']}), global {m['global']} ({m['kind']}), rule {m['rule']}. **{m['verdict']}**; cause: {m['cause']}; in step: {'—' if m['in_step'] is None else 'yes' if m['in_step'] else 'no'}. "
                 + (f"Runs: {', '.join(f'{r}: {v}' for r, v in m['history'])}. " if m['history'] else '') + (f"Note: {m['note']}" if m['note'] else ''))
        D.append('')
        if m['server']:
            sv = m['server']
            D.append(f"Server (build {sv['build']}): {'; '.join(sv['round_started'][:2])}; saves: {'; '.join(sv['save_lines'][-2:]) or 'none'}.")
            D.append('')
        D.append(census_line)
        for sn, s in m['seats'].items():
            if not s.get('lines'):
                D.append(f'- Seat {sn}: no log kept.')
                continue
            ex = {True: 'executed', False: 'NOT executed', None: 'execute not logged'}[s.get('executed')]
            won = f"won by diagnostic at {s['won'][0]} ({s['won'][1]} objectives completed)" if s.get('won') else 'not won'
